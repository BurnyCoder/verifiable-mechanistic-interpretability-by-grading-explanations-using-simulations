"""What the simulator agents actually did: excerpts of their own transcripts and build scripts, chosen by fixed rules.

Local explanation: `pick_runs` chooses example runs by rules stated in RULES (first replicate of a condition, or an
extreme of a stored metric), never by reading the transcripts first. `extract` parses one run's event log (Claude
Code stream-json for Claude runs, the bash harness's event log for local models) and its final `build_weights.py`:
tool calls, self-test runs and their last output, errors, the one-line "choice" comments the task asks the agent to
leave where the explanation is silent, the lines that set the frequencies, and the agent's closing message.
Global context: `tables.agent_examples_table` renders a compact table for the README, `write_doc` the full excerpts
to reports/agent-examples.md; both are regenerated by `vmi analyse`. Full transcripts are on the Hugging Face repo.
Sources: Claude Code stream-json events (types assistant / user / result; https://code.claude.com/docs/en/headless);
the bash harness's own event types (text, tool_use, error) in `simulator/harness.py`.
"""

from __future__ import annotations  # postponed annotations

import json  # event logs
import re  # code-line patterns

from vmi.analysis.hypotheses import LOCAL_MODELS, MAIN_MODEL, compiler, load_runs  # run records
from vmi.config import REPO_ROOT, load  # paths

HF_RUNS = "https://huggingface.co/BurnyCoder/grading-explanations-by-simulation/tree/main/replacements/"
RULES = [  # (label, kind, rule in words); the rule, not the outcome, decides which run is shown
    ("success", "✅", "first replicate of the true explanation E3 on T0"),
    ("beats the compiler", "✅", "largest agent-minus-compiler HS over true explanations on any target"),
    ("faithful to a wrong explanation", "✅", "first replicate of W-freq on T0 (the grader must catch it)"),
    ("fills gaps from memory", "❌", "first replicate of the algorithm-only explanation E1 on T0"),
    ("broken answers", "❌", "lowest task accuracy among the main simulator's runs"),
    ("small local model", "❌", "first local-model run on E3"),
]
CHOICE = re.compile(r"#.*\b(choice|not specified|unspecified|assum\w*|not given)\b", re.I)
INT_LIST = re.compile(r"^\s*\w+\s*=\s*[\[(]\s*\d+\s*(,\s*\d+\s*){2,}[\])]")  # ≥ 3 integers, e.g. KF = [2, 3, 23, 37, 39]
FREQS = re.compile(r"^\s*\w*(freq|FREQ)\w*\s*=\s*[\[(np]")


def _seed_first(rs):
    return sorted(rs, key=lambda r: (int(r.get("round", 0)), r["seed"]))[0] if rs else None


def pick_runs(max_round: int) -> list[tuple[tuple, dict]]:
    runs = [r for r in load_runs(max_round) if not r.get("failed")]
    main = [r for r in runs if r["model"] == MAIN_MODEL and r.get("variant", "") == ""]

    def first(**kw):
        return _seed_first([r for r in main if all(r.get(k) == v for k, v in kw.items())])

    def gap(r):
        c = compiler(r["target"], r["level"])
        return r["hs"] - c["hs"] if c else -9
    true = [r for r in main if r["level"] in ("E2", "E3", "E4")]
    local = _seed_first([r for r in runs if r["model"] in LOCAL_MODELS and r["level"] == "E3"])
    picks = [first(target="T0", level="E3"), max(true, key=gap) if true else None, first(target="T0", level="W-freq"),
             first(target="T0", level="E1"),
             min([r for r in runs if r["model"] == MAIN_MODEL], key=lambda r: r["accuracy"], default=None), local]
    return [(rule, r) for rule, r in zip(RULES, picks) if r]


def _claude_events(ev):
    calls, results, final, cost, says = [], [], "", None, []
    for e in ev:
        if e.get("type") == "assistant":
            for c in e["message"].get("content", []):
                if c.get("type") == "tool_use":
                    calls.append(c.get("input", {}).get("command") or json.dumps(c.get("input", {}))[:200])
                elif c.get("type") == "text" and c.get("text", "").strip():
                    final = c["text"]
                    says.append((len(calls), c["text"]))  # narration between tool calls (thinking is not returned)
        elif e.get("type") == "user":
            for c in e.get("message", {}).get("content", []):
                if isinstance(c, dict) and c.get("type") == "tool_result":
                    body = c.get("content")
                    results.append(body if isinstance(body, str) else " ".join(x.get("text", "") for x in body or [] if isinstance(x, dict)))
        elif e.get("type") == "result":
            cost = e.get("total_cost_usd")
    return calls, results, final, cost, [], says


def _harness_events(ev):
    calls, results, final, errors, says = [], [], "", [], []
    for e in ev:
        part = e.get("part", {})
        if e.get("type") == "tool_use":
            st = part.get("state", {})
            calls.append(st.get("input", {}).get("command", ""))
            results.append(st.get("output", ""))
        elif e.get("type") == "text" and not part.get("text", "").startswith("[harness]"):
            final = re.sub(r"```.*?(```|$)", "", part.get("text", ""), flags=re.S).replace("THOUGHT:", "").strip()
            if final:
                says.append((len(calls), final))  # the model's words without the command block
        elif e.get("type") == "text" and "exit status" in part.get("text", ""):
            errors.append(part["text"].replace("[harness] ", ""))  # e.g. "exit status: TimeExceeded"
        elif e.get("type") == "error":
            errors.append(part.get("error", {}).get("type", "error"))  # e.g. "output-limit": reply cut off, nothing ran
    return calls, results, final, None, errors, says


def first_sentence(text: str, n: int = 220) -> str:
    """The first sentence, or the first n characters cut at a word boundary."""
    text = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s if len(s) <= n else s[: s.rfind(" ", 0, n)] + " …"


def _short(text: str, n: int = 260) -> str:
    text = " ".join(text.split())
    if len(text) <= n:
        return text
    cut = text[:n]
    return (cut[: cut.rfind(". ") + 1] if ". " in cut[n // 2:] else cut.rstrip() + " …")


def extract(r: dict) -> dict:
    """Parsed facts about one run, all read from its own event log, build script and result record."""
    run = load().runs_dir / r["run_id"]
    ev = [json.loads(x) for x in (run / "logs" / "events.ndjson").read_text(encoding="utf-8").splitlines() if x.strip()]
    calls, results, final, cost, harness_errors, says = (_claude_events if r.get("harness") == "claudecode" else _harness_events)(ev)
    selftests = [i for i, c in enumerate(calls) if "selftest" in (c or "")]
    accs = [float(m.group(1)) for i in selftests if i < len(results)
            for m in [re.search(r"accuracy[^:\n]*:\s*([0-9]*\.[0-9]+)", results[i])] if m]  # self-test accuracy, in order
    talk = [s for n, s in says if s.strip() and s != final]
    plan = talk[0] if talk else ""
    reaction = next((s for n, s in says if selftests and n > selftests[0] and s != final and s != plan), "")
    last_st = next((results[i] for i in reversed(selftests) if i < len(results) and "ccuracy" in results[i]), "")
    acc_line = next((ln.strip() for ln in last_st.splitlines() if "ccuracy" in ln), "")
    script = run / "work_out" / "build_weights.py"
    lines = script.read_text(encoding="utf-8", errors="replace").splitlines() if script.exists() else []
    c = compiler(r["target"], r["level"])
    return {"run_id": r["run_id"], "target": r["target"], "level": r["level"] + (f" · {r['variant']}" if r.get("variant") else ""),
            "model": r["model"],
            "tool_calls": len(calls), "selftest_runs": len(selftests), "minutes": round((r.get("agent") or {}).get("seconds", 0) / 60, 1),
            "cost_usd": cost, "errors": sum(("Traceback" in x or "Error" in x) for x in results),
            "harness_errors": harness_errors, "last_selftest": acc_line,
            "choices": [ln.strip() for ln in lines if CHOICE.search(ln)][:3],
            "freq_lines": ([ln.strip() for ln in lines if INT_LIST.search(ln)] or [ln.strip() for ln in lines if FREQS.search(ln)])[:2],
            "final": _short(final, 420), "plan": _short(plan, 330), "reaction": _short(reaction, 330), "accs": accs,
            "said": [_short(s, 600) for _, s in says],
            "accuracy": r["accuracy"], "hs": r["hs"], "compiler_hs": c["hs"] if c else None, "url": HF_RUNS + r["run_id"]}


def sentence_with(text: str, needles: list[str], n: int = 200) -> str:
    """The first sentence of text that contains one of the needles (else the first sentence), cut to n characters."""
    sents = re.split(r"(?<=[.!?])\s+", " ".join(text.split()))
    s = next((x for x in sents if any(k in x for k in needles)), sents[0] if sents else "")
    return s if len(s) <= n else s[: s.rfind(" ", 0, n)] + " …"


def _freqs(line: str) -> list[int] | None:
    """The integer list in a line such as 'KF = [2, 3, 23, 37, 39]  # …' (only from INT_LIST-style lines)."""
    return [int(v) for v in re.findall(r"\d+", line.split("#")[0].split("=", 1)[1])] if line and INT_LIST.search(line) else None


def why(x: dict, target: str, level: str) -> str:
    """Why the run is right or wrong, from what it built (its script), what it was told, what the target uses, and
    what it said. Every value comes from the run's files, the explanation's spec and the target's analysis."""
    from vmi.analysis.frequencies import PAPER_FREQS
    base = REPO_ROOT / "results" / "explanations" / target
    tgt = json.loads((base / "analysis.json").read_text())["key_freqs"]
    spec = base / level.split(" · ")[0] / "spec.json"
    told = json.loads(spec.read_text()).get("embed_freqs") if spec.exists() else None
    built = _freqs((x["freq_lines"] or [""])[0])
    fs = lambda v: "{" + ", ".join(map(str, v)) + "}"  # noqa: E731
    acc, hs, accs = x["accuracy"], x["hs"], x["accs"]
    if acc < 0.05:
        cut = x["harness_errors"].count("output-limit")
        return (f"Wrong: it never built a working network. Its self-test stayed at chance ({accs[-1]:.4f}) every time"
                + (f"; {cut} of its replies were cut off at the output limit before anything ran" if cut else "")
                + (f", and the run ended with {x['harness_errors'][-1]}" if x["harness_errors"] else "")
                + (f". Its script even had the target's frequencies {fs(built)}" if built and set(built) == set(tgt) else "")
                + f". Its last words were still debugging: “{first_sentence(x['final'], 160)}”")
    if built and set(built) & set(PAPER_FREQS) and len(set(built) & set(PAPER_FREQS)) >= 3 and target != "T-paper" and not told:
        return (f"Wrong mechanism, right answers: the explanation gave no frequencies, and the agent filled "
                f"them in from memory (“{sentence_with(x['plan'], [str(v) for v in built], 120)}”). It built {fs(built)}, the published paper's "
                f"frequencies, instead of {target}'s {fs(tgt)}, so its answers are right (accuracy {acc:.4f}) but its "
                f"internals do not match (HS {hs:.2f}).")
    if told and built and set(built) == set(told) and set(told) != set(tgt):
        return (f"Right behaviour of the agent, and the grader catches the explanation: it built exactly the wrong "
                f"frequencies it was told, {fs(built)}, not {target}'s {fs(tgt)}. The answers are still right (accuracy "
                f"{acc:.4f}), but the internals do not match (HS {hs:.2f}), so HS exposes the wrong explanation that "
                f"output-only grading would pass.")
    if acc < 0.95:
        best = max(accs) if accs else acc
        return (f"Wrong answers, right mechanism: it built the target's frequencies {fs(built or tgt)}, so the internals "
                f"match (HS {hs:.2f}), but the details were off (accuracy {acc:.4f}). It noticed (“{sentence_with(x['reaction'] or x['final'], ['ccuracy', '%'], 150)}”), "
                f"its self-test peaked at {best:.4f} and it stopped on a build at {acc:.4f}, because each rewrite replaced the last.")
    c = x["compiler_hs"]
    if c is not None and hs > c + 0.05:
        return (f"Right, and better than the AI-free compiler: it built {target}'s frequencies {fs(built or tgt)} and "
                f"debugged its way from a first self-test at {accs[0]:.4f} to {accs[-1]:.4f} (“{sentence_with(' '.join(x['said']), ['ccuracy', '%'], 170)}”). "
                f"HS {hs:.2f} against the compiler's {c:.2f}, which follows the rendered explanation literally.")
    return (f"Right: it built exactly the frequencies the explanation names, {fs(built or tgt)}, which are {target}'s own, "
            f"so both the answers (accuracy {acc:.4f}) and the internals (HS {hs:.2f}"
            + (f"; compiler {c:.2f}" if c is not None else "") + ") match the target.")


def rows(max_round: int) -> list[dict]:
    out = []
    for (label, kind, rule), r in pick_runs(max_round):
        try:
            x = {"label": label, "kind": kind, "rule": rule, **extract(r)}
        except FileNotFoundError:  # run folder not on this machine (e.g. a fresh clone): skip, never invent
            continue
        x["why"] = why(x, r["target"], r["level"])
        out.append(x)
    return out


def write_doc(max_round: int) -> str:
    """Full excerpts to reports/agent-examples.md; returns the path."""
    parts = [f"# What the simulator agents did: examples from their own transcripts (round {max_round})", "",
             "Generated by `vmi analyse` from each run's event log and final `build_weights.py`; runs are chosen by the "
             "rule shown, not by reading transcripts first. Full transcripts, wire logs and weights: linked per run.", ""]
    for x in rows(max_round):
        parts += [f"## {x['kind']} {x['label']} — `{x['run_id']}`", "", f"*Chosen by rule:* {x['rule']}.", "",
                  f"**Why:** {x['why']}", "",
                  f"- **Result:** task accuracy {x['accuracy']:.4f}, HS {x['hs']:.3f}"
                  + (f" (reference compiler on the same explanation: {x['compiler_hs']:.3f})" if x["compiler_hs"] is not None else ""),
                  f"- **Process:** {x['tool_calls']} tool calls, {x['selftest_runs']} self-test runs, {x['errors']} tool "
                  f"outputs with an error, {x['minutes']} minutes" + (f", ${x['cost_usd']:.3f}" if x["cost_usd"] else ""),
                  f"- **Last self-test output:** `{x['last_selftest'] or 'none'}`"]
        if x["harness_errors"]:
            counts = {e: x["harness_errors"].count(e) for e in dict.fromkeys(x["harness_errors"])}
            parts.append("- **Harness events:** " + ", ".join(f"{e} ×{n}" if n > 1 else e for e, n in counts.items()))
        if x["freq_lines"] or x["choices"]:
            parts += ["- **Lines it wrote in `build_weights.py`:**", "", "```python", *x["freq_lines"], *x["choices"], "```"]
        if x["accs"]:
            parts.append("- **Self-test accuracy over the run:** " + " → ".join(f"{a:.4f}" for a in x["accs"]))
        parts += ["", "**What it said, in order** (its messages between tool calls; the model's hidden thinking is not "
                  "returned by the API):", ""]
        parts += [f"{i}. {s}" for i, s in enumerate(x["said"], 1)] or ["(nothing)"]
        parts += ["", f"[Full transcript and weights]({x['url']})", ""]
    path = REPO_ROOT / "reports" / "agent-examples.md"
    path.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    return str(path)
