"""Markdown tables generated from results/ (no hand-typed numbers): compiler scores, agent runs, hypothesis verdicts.

Local explanation: `compiler_table(target)` lists each explanation level's reference-compiler scores; `runs_table(round)`
aggregates agent runs per condition (mean ± sd, N, failure rate); `hypotheses_table(round)` lists verdicts with their N.
`inject(path, name, text)` replaces the block between `<!-- BEGIN name -->` and `<!-- END name -->` in a markdown file,
so README, experiment reports and the paper source are regenerated by one command (`vmi report`).
"""

from __future__ import annotations  # postponed annotations

import json  # results
import re  # marker replacement
from collections import defaultdict  # grouping
from pathlib import Path  # paths

import numpy as np  # aggregates

from vmi.config import REPO_ROOT  # results folder

RES = REPO_ROOT / "results"
LEVEL_ORDER = ["E0", "E1", "E2", "E3", "E4", "W-freq", "W-alg", "W-role", "W-scramble", "E-paper", "E3-fmt-math", "E3-fmt-code"]


def _f(x, nd=3):
    if x is None:
        return "–"
    if isinstance(x, float) and (abs(x) < 1e-3 or abs(x) >= 1e4) and x != 0:
        return f"{x:.2e}"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def _t(temp) -> str:
    """Sampling temperature as text; None means the simulator's default sampling (Claude 5.5 accepts no other)."""
    return "default" if temp is None else f"{temp:g}"


def compiler_table(target: str) -> str:
    """Reference-compiler scores for every level of one target."""
    d = RES / "compiler" / target
    rows = ["| Explanation | chars | task accuracy | KL_out ↓ | HS ↑ | resid_mid | mlp_post | resid_post | matched neuron corr |",
            "|---|---|---|---|---|---|---|---|---|"]
    for lv in LEVEL_ORDER:
        p = d / f"{lv}.json"
        if not p.exists():
            continue
        r = json.loads(p.read_text())
        L = RES / "explanations" / target / lv / "length.json"
        chars = json.loads(L.read_text())["chars"] if L.exists() else None
        s = r["sites"]
        rows.append(f"| {lv} | {chars} | {_f(r['accuracy'], 4)} | {_f(r['kl_out'])} | {_f(r['hs'])} | {_f(s['resid_mid']['harmonic'])} | "
                    f"{_f(s['mlp_post']['harmonic'])} | {_f(s['resid_post']['harmonic'])} | {_f(r.get('matched_neuron_corr'))} |")
    return "\n".join(rows)


def runs_table(max_round: int) -> str:
    """Agent runs aggregated per (stage, target, level, model, temperature, variant)."""
    groups = defaultdict(list)
    for p in sorted((RES / "runs").glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("stage") == "dev" or int(r.get("round", 0)) > max_round:
            continue
        groups[(r["stage"], r["target"], r["level"], r["model"], _t(r["temperature"]), r.get("variant", ""))].append(r)
    rows = ["| Stage | Target | Explanation | Simulator | T | Variant | N | failed | accuracy | KL_out ↓ (mean ± sd) | HS ↑ (mean ± sd) |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(groups, key=lambda k: (k[0], k[1], LEVEL_ORDER.index(k[2]) if k[2] in LEVEL_ORDER else 99, k[3], k[4], k[5])):
        rs = groups[k]
        hs = np.array([r["hs"] for r in rs])
        kl = np.array([r["kl_out"] for r in rs])
        acc = np.array([r["accuracy"] for r in rs])
        sd = lambda a: f" ± {a.std(ddof=1):.3g}" if len(a) > 1 else ""  # noqa: E731
        rows.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {k[5] or '–'} | {len(rs)} | {sum(r['failed'] for r in rs)} | "
                    f"{acc.mean():.3f} | {kl.mean():.3g}{sd(kl)} | {hs.mean():.3f}{sd(hs)} |")
    return "\n".join(rows)


def hypotheses_table(max_round: int) -> str:
    """One row per hypothesis with its verdict and N label."""
    p = RES / f"hypotheses_round{max_round}.json"
    if not p.exists():
        return "_not evaluated yet_"
    H = json.loads(p.read_text())["hypotheses"]
    rows = ["| Hypothesis | Verdict | Evidence size |", "|---|---|---|"]
    for k in ("H1", "H2", "H3", "H4", "H4b", "H5", "H6", "H7", "H8"):
        if k not in H:
            rows.append(f"| {k} | not evaluated yet | – |")
            continue
        h = H[k]
        v = h.get("verdict") or "; ".join(f"{a}: {b}" for a, b in h.get("verdicts", {}).items())
        rows.append(f"| {k} | {v} | {h.get('label', h.get('N', h.get('N_runs', '–')))} |")
    return "\n".join(rows)


def _ms(vals, nd=3) -> str:
    """'mean ± sd' (sample sd, ddof=1) for ≥ 2 values, the value itself for one, '–' for none."""
    a = np.asarray([v for v in vals if v is not None], float)
    if not len(a):
        return "–"
    m = _f(float(a.mean()), nd)
    return f"{m} ± {_f(float(a.std(ddof=1)), nd)}" if len(a) > 1 else m


def _chars(target: str, level: str):
    L = RES / "explanations" / target / level / "length.json"
    return json.loads(L.read_text())["chars"] if L.exists() else None


def scoreboard(max_round: int, target: str = "T0") -> str:
    """Main simulator's runs next to the agent-free reference compiler, per explanation of one target.

    Rows are the main method (true ladder) and the agent controls (no / wrong explanation) at the main simulator's
    preregistered settings; the compiler columns show what the same explanation yields with no agent at all."""
    from vmi.analysis.hypotheses import _select, load_runs  # same condition selection as the hypothesis tests
    runs = [r for r in load_runs(max_round) if not r.get("failed")]
    rows = ["| Explanation | role | chars | N | agent accuracy | agent KL_out ↓ | agent HS ↑ | agent matched-neuron corr ↑ "
            "| compiler KL_out ↓ | compiler HS ↑ |", "|---|---|---|---|---|---|---|---|---|---|"]
    roles = {"E0": "control: no mechanism", "E1": "method", "E2": "method", "E3": "method", "E4": "method",
             "W-freq": "control: wrong frequencies", "W-alg": "control: wrong algorithm (Pizza)",
             "W-role": "control: wrong component roles", "W-scramble": "control: scrambled neurons", "E-paper": "published text"}
    for lv in LEVEL_ORDER:
        rs = _select(runs, target=target, level=lv)
        c = (RES / "compiler" / target / f"{lv}.json")
        c = json.loads(c.read_text()) if c.exists() else None
        if not rs and not c:
            continue
        rows.append(f"| {lv} | {roles.get(lv, '')} | {_chars(target, lv)} | {len(rs)} | {_ms([r['accuracy'] for r in rs])} | "
                    f"{_ms([r['kl_out'] for r in rs])} | {_ms([r['hs'] for r in rs])} | {_ms([r.get('matched_neuron_corr') for r in rs])} | "
                    f"{_f(c['kl_out']) if c else '–'} | {_f(c['hs']) if c else '–'} |")
    return "\n".join(rows)


def baselines_table(target: str = "T0") -> str:
    """No-agent reference points (preregistration §7): what you get without an agent or without an explanation."""
    rows = ["| Reference point | what it has | n | task accuracy | KL_out ↓ | HS ↑ |", "|---|---|---|---|---|---|"]
    b = RES / "baselines" / f"{target}.json"
    ri = RES / "controls" / f"random_init_{target}.json"
    entries = []
    if ri.exists():
        entries.append(("Random initialisation", "nothing (floor)", json.loads(ri.read_text())))
    if b.exists():
        d = json.loads(b.read_text())
        entries += [("Independent retrains", "same recipe, other seeds", d["retrains"]),
                    ("Logit-distilled students", "M's full output logits, no explanation", d["students"]),
                    ("Fourier-restricted M", "M's weights, key frequencies only in W_E/W_U", [d["fourier_restricted"]]),
                    ("Weights dump", f"all {d['weights_dump_length']['numbers']:,} weights", [d["weights_dump"]])]
    for name, has, rs in entries:
        rows.append(f"| {name} | {has} | {len(rs)} | {_ms([r['accuracy'] for r in rs])} | {_ms([r['kl_out'] for r in rs])} | "
                    f"{_ms([r['hs'] for r in rs])} |")
    return "\n".join(rows)


def controls_table(target: str = "T0", max_round: int | None = None) -> str:
    """Deterministic no-agent controls: planted-mechanism calibration (H4b) and wrong-target specificity (H7).

    The wrong-target file is refreshed every round; with max_round only that round's replacements are listed."""
    out = []
    pc = RES / "controls" / f"planted_calibration_{target}.json"
    if pc.exists():
        out += ["| Planted model trained further (steps) | HS ↑ | KL_out | snapshot task accuracy |", "|---|---|---|---|"]
        out += [f"| {r['step']} | {_f(r['hs'])} | {_f(r['kl_out'])} | {_f(r['snapshot_accuracy'], 4)} |"
                for r in json.loads(pc.read_text())["rows"]]
    wt = RES / "controls" / f"wrong_targets_{target}.json"
    if wt.exists():
        rows = json.loads(wt.read_text())["rows"]
        if max_round is not None:
            from vmi.analysis.hypotheses import load_runs
            keep = {r["run_id"] for r in load_runs(max_round)}
            rows = [r for r in rows if r["run_id"] in keep]
        out += ["", "| Replacement | HS vs T0 | best wrong target (HS) | d = HS(T0) − max HS(wrong) |", "|---|---|---|---|"]
        for r in rows:
            k = max(r["hs_wrong"], key=r["hs_wrong"].get)
            out.append(f"| {r['level']} | {_f(r['hs_T0'])} | {k} ({_f(r['hs_wrong'][k])}) | {_f(r['d'])} |")
    return "\n".join(out) if out else "_not run yet_"


def key_results(max_round: int, target: str = "T0") -> str:
    """Headline sentences for the abstract, README and summary, with every number read from results/."""
    from vmi.analysis.hypotheses import _select, load_runs
    runs = [r for r in load_runs(max_round) if not r.get("failed")]
    m = lambda lv, k="hs": (lambda rs: float(np.mean([r[k] for r in rs])) if rs else None)(_select(runs, target=target, level=lv))  # noqa: E731
    n = min((len(_select(runs, target=target, level=lv)) for lv in ("E1", "E2", "E3", "E4")), default=0)
    out = [f"*Round {max_round}, N = {n} run(s) per condition"
           + (" — not yet N=3 or N=10*" if n == 1 else " — not yet N=10*" if n == 3 else "*")]
    if all(m(lv) is not None for lv in ("E1", "E2", "E3", "E4")):
        lv4 = ("E1", "E2", "E3", "E4")
        inv = [f"{b} < {a}" for a, b in zip(lv4, lv4[1:]) if m(b) < m(a)]  # order violations along the ladder
        out.append(f"- **Model-specific detail raises hidden-state similarity:** HS on {target} is {m('E1'):.2f} (E1, algorithm "
                   f"only), {m('E2'):.2f} (E2), {m('E3'):.2f} (E3) and {m('E4'):.2f} (E4); with no explanation (E0) it is "
                   f"{_f(m('E0'), 2)}. " + (f"Not monotone: {', '.join(inv)}." if inv else "Monotone along the ladder."))
    if m("W-freq") is not None:
        out.append(f"- **Correct behaviour, wrong mechanism is caught by HS, not by output KL:** the wrong-frequency "
                   f"replacement reaches KL {_f(m('W-freq', 'kl_out'))} nats (true E3: {_f(m('E3', 'kl_out'))}) but HS "
                   f"{m('W-freq'):.2f}.")
    b = RES / "baselines" / f"{target}.json"
    ri = RES / "controls" / f"random_init_{target}.json"
    if b.exists() and ri.exists():
        d, r0 = json.loads(b.read_text()), json.loads(ri.read_text())
        hs = lambda rs: float(np.mean([x["hs"] for x in rs]))  # noqa: E731
        out.append(f"- **Copying behaviour does not copy the mechanism:** independent retrains (HS {hs(d['retrains']):.2f}) and "
                   f"logit-distilled students (HS {hs(d['students']):.2f}, KL {_f(float(np.mean([x['kl_out'] for x in d['students']])))}) "
                   f"stay at the random-initialisation floor (HS {hs(r0):.2f}).")
    if m("W-alg") is not None and m("W-scramble") is not None:
        out.append(f"- **Negative result:** the primary HS does not separate the Pizza explanation (W-alg, HS {m('W-alg'):.2f}) "
                   f"or the scrambled neuron table (W-scramble, HS {m('W-scramble'):.2f}) from the true explanations; the "
                   f"secondary matched-neuron correlation separates W-scramble ({_f(m('W-scramble', 'matched_neuron_corr'), 2)}) "
                   f"from E4 ({_f(m('E4', 'matched_neuron_corr'), 2)}).")
    fq = RES / f"frequencies_round{max_round}.json"
    tp_e1 = [r for r in runs if r["target"] == "T-paper" and r["level"] == "E1" and r.get("variant", "") == "" and r["model"] == "claude-haiku-5-5"]
    if fq.exists() and tp_e1 and m("E1") is not None:
        rows = [r for r in json.loads(fq.read_text())["rows"] if r["model"] == "claude-haiku-5-5" and r["variant"] == ""
                and r["level"] in ("E0", "E1") and r["target"] != "T-paper"]
        if rows:
            def per_level(lv):  # replicates differ (round 2: some E0 runs build blocks of consecutive frequencies instead)
                rs = [r for r in rows if r["level"] == lv]
                if not rs:
                    return ""
                mem = sum(r["jaccard_paper"] >= 0.5 for r in rs)
                swap = [r["hs_vs_paper"] for r in rs if "hs_vs_paper" in r]
                return (f"{lv}: {mem} of {len(rs)} replacement(s) built mostly the paper's frequencies (Jaccard ≥ 0.5); mean HS "
                        f"{np.mean([r['hs'] for r in rs]):.2f} against {rs[0]['target']} but "
                        f"{np.mean(swap):.2f} against the published checkpoint (target swap: same weights, other target)")
            out.append(f"- **Memorisation (post hoc):** when the explanation gives no frequencies, the simulator often builds "
                       f"the published paper's frequencies {{14, 35, 41, 42, 52}} into its replacement. "
                       + "; ".join(x for x in (per_level("E1"), per_level("E0")) if x)
                       + f". A separate algorithm-only run on the published checkpoint scores HS "
                       f"{np.mean([r['hs'] for r in tp_e1]):.2f}: scores on published models measure memory, not the explanation.")
    led = RES / "claude" / "ledger.jsonl"
    if led.exists():
        spend = sum(json.loads(x).get("cost_usd", 0.0) for x in led.read_text(encoding="utf-8").splitlines() if x.strip())
        out.append(f"- **Cost:** all Claude Haiku 5.5 runs so far cost ${spend:.2f} in total.")
    return out[0] + "\n\n" + "\n".join(out[1:])  # blank line: a markdown list must not continue the paragraph above


def grader_sensitivity_table(max_round: int, target: str = "T0", kind: str = "agent") -> str:
    """Mean HS per explanation under each preregistered grader variant, and Kendall τ of the ordering vs. default."""
    p = RES / "sensitivity" / f"grader_{target}_round{max_round}.json"
    if not p.exists():
        return "_not run yet_"
    d = json.loads(p.read_text())
    S = d["summary"][kind]
    levels = [lv for lv in LEVEL_ORDER if any(lv in v["means"] for v in S.values())]
    rows = ["| Grader setting | " + " | ".join(levels) + " | Kendall τ vs. preregistered |", "|---" * (len(levels) + 2) + "|"]
    for name, v in S.items():
        rows.append(f"| {name} | " + " | ".join(_f(v["means"].get(lv), 2) for lv in levels) + f" | {_f(v['kendall_tau_vs_preregistered'], 2)} |")
    return "\n".join(rows)


def explainer_sensitivity_table(target: str = "T0") -> str:
    """Reference-compiler HS of E2–E4 when the explainer's thresholds change (no agent)."""
    p = RES / "sensitivity" / f"explainer_{target}.json"
    if not p.exists():
        return "_not run yet_"
    rows = json.loads(p.read_text())["rows"]
    out = ["| key-frequency τ | neuron FVE threshold | key frequencies found | compiler HS E2 | E3 | E4 |", "|---|---|---|---|---|---|"]
    seen = []
    for r in rows:
        k = (r["tau"], r["neuron_fve"])
        if k in seen:
            continue
        seen.append(k)
        hs = {x["level"]: x["hs"] for x in rows if (x["tau"], x["neuron_fve"]) == k}
        out.append(f"| {r['tau']} | {r['neuron_fve']} | {', '.join(map(str, r['key_freqs']))} | {_f(hs.get('E2'))} | "
                   f"{_f(hs.get('E3'))} | {_f(hs.get('E4'))} |")
    return "\n".join(out)


def frequencies_table(max_round: int, model: str = "claude-haiku-5-5") -> str:
    """Post hoc: frequencies each replacement uses vs. the target's and the paper's (memorisation check)."""
    p = RES / f"frequencies_round{max_round}.json"
    if not p.exists():
        return "_not computed yet_"
    d = json.loads(p.read_text())
    rows = ["| Target | Explanation | frequencies used by the replacement | target's key frequencies | overlap with target (Jaccard) | overlap with paper's {14, 35, 41, 42, 52} | HS | same weights: HS against the published checkpoint |",
            "|---|---|---|---|---|---|---|---|"]
    order = {t: i for i, t in enumerate(["T0", "T1", "T2", "T-new", "T-paper"])}
    for r in sorted((x for x in d["rows"] if x["model"] == model and x["variant"] == ""),
                    key=lambda x: (order.get(x["target"], 9), LEVEL_ORDER.index(x["level"]) if x["level"] in LEVEL_ORDER else 99)):
        rows.append(f"| {r['target']} | {r['level']} | {', '.join(map(str, r['used_freqs']))} | {', '.join(map(str, r['target_freqs']))} | "
                    f"{r['jaccard_target']:.2f} | {r['jaccard_paper']:.2f} | {r['hs']:.3f} | {_f(r.get('hs_vs_paper'), 3)} |")
    return "\n".join(rows)


def ablations_table(max_round: int, target: str = "T0") -> str:
    """Ablation and hyperparameter variants next to the unablated condition (main simulator) and the local simulators."""
    from vmi.analysis.hypotheses import LOCAL_MODELS, MAIN_MODEL, _select, load_runs
    runs = load_runs(max_round)
    spec = [("none (main condition)", "E3", "", MAIN_MODEL), ("explanation as maths", "E3", "fmt-math", MAIN_MODEL),
            ("explanation as code", "E3", "fmt-code", MAIN_MODEL), ("self-test removed", "E3", "noselftest", MAIN_MODEL),
            ("effort low", "E3", "effort-low", MAIN_MODEL), ("effort high", "E3", "effort-high", MAIN_MODEL),
            ("none (main condition)", "W-freq", "", MAIN_MODEL), ("effort low", "W-freq", "effort-low", MAIN_MODEL),
            ("effort high", "W-freq", "effort-high", MAIN_MODEL)]
    spec += [(f"simulator {m}", lv, "", m) for m in LOCAL_MODELS for lv in ("E2", "E3", "E4", "W-freq")]
    rows = ["| Change | Explanation | Simulator | N | task accuracy | KL_out ↓ | HS ↑ | matched-neuron corr ↑ |",
            "|---|---|---|---|---|---|---|---|"]
    for change, lv, variant, model in spec:
        rs = [r for r in _select(runs, target=target, level=lv, variant=variant, model=model) if not r.get("failed")]
        if rs:
            rows.append(f"| {change} | {lv} | {model} | {len(rs)} | {_ms([r['accuracy'] for r in rs])} | "
                        f"{_ms([r['kl_out'] for r in rs])} | {_ms([r['hs'] for r in rs])} | "
                        f"{_ms([r.get('matched_neuron_corr') for r in rs])} |")
    return "\n".join(rows)


def predictions_table(max_round: int, plain: bool = False) -> str:
    """Preregistered prediction vs. observation per hypothesis (main simulator), with the formal verdict beside it.

    plain=True adds the prediction in plain words (README top); the paper and reports use the expert columns only."""
    from vmi.analysis.predictions import prediction_rows
    rows = prediction_rows(max_round)
    if not rows:
        return "_not evaluated yet_"
    head = "| Hypothesis | " + ("Expected, in plain words | " if plain else "")
    out = [head + "Predicted (preregistration §5) | Measured with the main simulator (T0) | Direction matches? | Formal verdict |",
           "|---|" + ("-------|" if plain else "") + "-------|---------|-----|------|"]  # pandoc: dashes set PDF column widths
    out += [f"| {r['id']} | " + (f"{r['plain']} | " if plain else "") +
            f"{r['predicted']} | {r['observed']} | {r['matches']} | {r['verdict']} · {r['evidence']} |" for r in rows]
    return "\n".join(out)


def highlights_table(max_round: int) -> str:
    """What works (✅) and what does not (❌): concrete examples with numbers from results/ (README top)."""
    from vmi.analysis.hypotheses import _select, load_runs
    from vmi.analysis.predictions import highlight_rows
    rows = highlight_rows(max_round)
    if not rows:
        return "_no results yet_"
    n = len(_select(load_runs(max_round), level="E3"))
    out = [f"*Main simulator Claude Haiku 5.5, target T0 unless stated; means over {n} run(s) per condition (round {max_round}).*", "",
           "| | Example | Measured | What it means |", "|---|---|---|---|"]
    out += [f"| {'✅' if r['ok'] else '❌'} | **{r['title']}** | {r['evidence']} | {r['means']} |" for r in rows]
    return "\n".join(out)


def outputs_table(max_round: int, target: str = "T0") -> str:
    """Concrete answers of each example network on a few inputs, next to the true answer (README highlights)."""
    from vmi.analysis.examples import output_rows, panel_models
    from vmi.config import P
    panels = panel_models(max_round, target)
    inputs, answers, acc = output_rows(panels)
    names = [p["name"] for p in panels]
    out = ["| Input | True answer | " + " | ".join(n.replace("agent, ", "agent ") for n in names) + " |",
           "|---|---|" + "---|" * len(names)]
    for i, (a, b) in enumerate(inputs):
        truth = (a + b) % P
        cells = [f"{ans} {'✓' if ans == truth else '✗'} ({pr:.2f})" for ans, pr in (answers[n][i] for n in names)]
        out.append(f"| {a} + {b} | {truth} | " + " | ".join(cells) + " |")
    out.append(f"| **accuracy, all {P * P:,} inputs** | 1.000 | " + " | ".join(f"{acc[n]:.3f}" for n in names) + " |")
    out.append("| **HS (insides vs. target)** | – | " + " | ".join("1 (itself)" if p["kind"] == "target" else f"{p['hs']:.2f}"
                                                              for p in panels) + " |")
    return "\n".join(out)


def agent_examples_table(max_round: int) -> str:
    """What the agent did in example runs chosen by rule: process, a line it wrote, its own words, the result."""
    from vmi.analysis import agent_examples
    rows = agent_examples.rows(max_round)
    if not rows:
        return "_no agent runs on this machine_"
    esc = lambda s: s.replace("|", "\\|")  # noqa: E731  markdown table cells
    out = ["| | Case (run chosen by rule) | What the agent did (its log) | A line it wrote | In its own words (closing message) | Result |",
           "|---|---|---|---|---|---|"]
    for x in rows:
        line = " ".join((x["freq_lines"] or x["choices"] or ["–"])[0].split())
        line = line if len(line) <= 90 else line[:89] + "…"
        process = (f"{x['tool_calls']} tool calls, {x['selftest_runs']} self-tests, {x['errors']} errors, {x['minutes']} min"
                   + (f"; harness: {', '.join(dict.fromkeys(x['harness_errors']))}" if x["harness_errors"] else ""))
        first = agent_examples.first_sentence(x["final"])
        result = f"accuracy {x['accuracy']:.4f}, HS {x['hs']:.2f}" + (f" (compiler {x['compiler_hs']:.2f})" if x["compiler_hs"] is not None else "")
        out.append(f"| {x['kind']} | **{x['label']}**<br>[{x['target']} · {x['level']} · {x['model']}]({x['url']}) | {esc(process)} | "
                   f"`{esc(line)}` | {esc(first)} | {result} |")
    return "\n".join(out)


def agent_words_md(max_round: int) -> str:
    """The agent's own words in each example run: its plan, its reaction to the first self-test, its closing line."""
    from vmi.analysis import agent_examples
    rows = agent_examples.rows(max_round)
    if not rows:
        return "_no agent runs on this machine_"
    out = []
    for x in rows:
        traj = " → ".join(f"{a:.4f}" for a in x["accs"]) or "never reached"
        out += [f"**{x['kind']} {x['label']}** ({x['target']} · {x['level']} · {x['model']}; self-test accuracy over the "
                f"run: {traj}; final HS {x['hs']:.2f})", "", f"*Why:* {x['why']}", ""]
        quotes = [("Plan", x["plan"]), ("After the first self-test", x["reaction"]),
                  ("Closing", agent_examples.first_sentence(x["final"], 260))]
        out += [f"> *{k}:* “{q}”  " for k, q in quotes if q]
        out.append("")
    return "\n".join(out).rstrip()


def replications_table(max_round: int) -> str:
    """H1–H3 re-checked on the seed-sensitivity targets (preregistered replications)."""
    from vmi.analysis.predictions import replication_rows
    rows = replication_rows(max_round)
    if not rows:
        return "_not run yet_"
    out = ["| Target | HS per true explanation | H1: HS rises E2→E4? | H2: HS(E3) − HS(W-freq) | H3 observed (W-freq) | H3 holds? |",
           "|-----|------|---|---|-------|-----|"]
    out += [f"| {r['target']} | {r['hs_by_level']} | {r['h1']} | {r['h2']} | {r['h3_observed']} | {r['h3']} |" for r in rows]
    return "\n".join(out)


def stitching_table(max_round: int, target: str = "T0") -> str:
    """Secondary causal metric: stitching KL of the main simulator's and the compiler's replacements, next to HS."""
    from vmi.analysis.hypotheses import _select, compiler, load_runs
    runs = load_runs(max_round)
    rows = ["| Explanation | HS (agent) | stitching KL (agent) | HS (compiler) | stitching KL (compiler) |", "|---|---|---|---|---|"]
    for lv in LEVEL_ORDER:
        rs, c = _select(runs, target=target, level=lv), compiler(target, lv)
        if rs or c:
            rows.append(f"| {lv} | {_ms([r['hs'] for r in rs])} | {_ms([r.get('stitching_kl') for r in rs], 4)} | "
                        f"{_f(c and c['hs'])} | {_f(c and c.get('stitching_kl'), 4)} |")
    return "\n".join(rows)


def targets_table() -> str:
    """The trained target networks: run, role, key frequencies, neurons per frequency cluster, logit-fit quality."""
    from vmi import targets
    roles = {"T0": "main target", "T1": "seed sensitivity (fewest frequencies)", "T2": "seed sensitivity (most frequencies)",
             "T-new": "held-out, trained after the protocol freeze", "T-paper": "published checkpoint (contamination-flagged)",
             "dev": "development only (never reported)"}
    rows = ["| Target | run | role | key frequencies | neurons per key frequency | unclustered neurons | logit fit FVE | loss (all 113² inputs) |",
            "|---|---|---|---|---|---|---|---|"]
    for t, role in roles.items():
        a = RES / "explanations" / t / "analysis.json"
        if not a.exists():
            continue
        d = json.loads(a.read_text())
        cl = d["neuron_clusters"]
        n_un = d["neurons_unclustered"]
        rows.append(f"| {t} | `{targets.resolve(t).run_id}` | {role} | {', '.join(map(str, d['key_freqs']))} | "
                    f"{', '.join(str(len(cl[str(k)]) if isinstance(cl[str(k)], list) else cl[str(k)]) for k in d['key_freqs'])} | "
                    f"{len(n_un) if isinstance(n_un, list) else n_un} | {_f(d['logit_fit_fve'])} | {_f(d['loss_all_inputs'])} |")
    return "\n".join(rows)


def cost_table() -> str:
    """Claude API spend from the proxy's request ledger (every request, priced at the published rates)."""
    led = RES / "claude" / "ledger.jsonl"
    if not led.exists():
        return "_no Claude runs_"
    spend, reqs, runs = defaultdict(float), defaultdict(int), defaultdict(set)
    for line in led.read_text(encoding="utf-8").splitlines():
        if line.strip():
            d = json.loads(line)
            spend[d["model"]] += d.get("cost_usd", 0.0)
            reqs[d["model"]] += 1
            runs[d["model"]].add(d["run_id"])
    rows = ["| Model | runs (incl. checks) | requests | spend (USD) |", "|---|---|---|---|"]
    rows += [f"| {m} | {len(runs[m])} | {reqs[m]} | {spend[m]:.3f} |" for m in sorted(spend)]
    rows.append(f"| **total** | {len(set().union(*runs.values()))} | {sum(reqs.values())} | **{sum(spend.values()):.3f}** |")
    return "\n".join(rows)


def inject(path: Path, name: str, text: str) -> None:
    """Replace the marked block `name` in a markdown file (markers must already exist)."""
    s = path.read_text(encoding="utf-8")
    pat = re.compile(rf"(<!-- BEGIN {re.escape(name)} -->).*?(<!-- END {re.escape(name)} -->)", re.S)
    if not pat.search(s):
        raise KeyError(f"markers for {name} not found in {path}")
    path.write_text(pat.sub(lambda m: m.group(1) + "\n" + text.strip("\n") + "\n" + m.group(2), s), encoding="utf-8", newline="\n")
