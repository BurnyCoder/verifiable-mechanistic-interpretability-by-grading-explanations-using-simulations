"""Markdown tables generated from results/ (no hand-typed numbers): compiler scores, agent runs, hypothesis verdicts.

Local explanation: `compiler_table(target)` lists each explanation level's reference-compiler scores; `runs_table(round)`
aggregates agent runs per condition (mean ± sd, N, failure rate); `hypotheses_table(round)` lists verdicts with their N.
`inject(path, name, text)` replaces the block between `<!-- BEGIN name -->` and `<!-- END name -->` in a markdown file,
so README, experiment reports and the paper source are regenerated by one command (`vmi report`).
"""

from __future__ import annotations  # postponed annotations

import json  # results
import re  # marker replacement
from collections import defaultdict  # grouping
from pathlib import Path  # paths

import numpy as np  # aggregates

from vmi.config import REPO_ROOT  # results folder

RES = REPO_ROOT / "results"
LEVEL_ORDER = ["E0", "E1", "E2", "E3", "E4", "W-freq", "W-alg", "W-role", "W-scramble", "E-paper", "E3-fmt-math", "E3-fmt-code"]


def _f(x, nd=3):
    if x is None:
        return "–"
    if isinstance(x, float) and (abs(x) < 1e-3 or abs(x) >= 1e4) and x != 0:
        return f"{x:.2e}"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def compiler_table(target: str) -> str:
    """Reference-compiler scores for every level of one target."""
    d = RES / "compiler" / target
    rows = ["| Explanation | chars | task accuracy | KL_out ↓ | HS ↑ | resid_mid | mlp_post | resid_post | matched neuron corr |",
            "|---|---|---|---|---|---|---|---|---|"]
    for lv in LEVEL_ORDER:
        p = d / f"{lv}.json"
        if not p.exists():
            continue
        r = json.loads(p.read_text())
        L = RES / "explanations" / target / lv / "length.json"
        chars = json.loads(L.read_text())["chars"] if L.exists() else None
        s = r["sites"]
        rows.append(f"| {lv} | {chars} | {_f(r['accuracy'], 4)} | {_f(r['kl_out'])} | {_f(r['hs'])} | {_f(s['resid_mid']['harmonic'])} | "
                    f"{_f(s['mlp_post']['harmonic'])} | {_f(s['resid_post']['harmonic'])} | {_f(r.get('matched_neuron_corr'))} |")
    return "\n".join(rows)


def runs_table(max_round: int) -> str:
    """Agent runs aggregated per (stage, target, level, model, temperature, variant)."""
    groups = defaultdict(list)
    for p in sorted((RES / "runs").glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("stage") == "dev" or int(r.get("round", 0)) > max_round:
            continue
        groups[(r["stage"], r["target"], r["level"], r["model"], r["temperature"], r.get("variant", ""))].append(r)
    rows = ["| Stage | Target | Explanation | Simulator | T | Variant | N | failed | accuracy | KL_out ↓ (mean ± sd) | HS ↑ (mean ± sd) |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(groups, key=lambda k: (k[0], k[1], LEVEL_ORDER.index(k[2]) if k[2] in LEVEL_ORDER else 99, k[3], k[4], k[5])):
        rs = groups[k]
        hs = np.array([r["hs"] for r in rs])
        kl = np.array([r["kl_out"] for r in rs])
        acc = np.array([r["accuracy"] for r in rs])
        sd = lambda a: f" ± {a.std(ddof=1):.3g}" if len(a) > 1 else ""  # noqa: E731
        rows.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]:g} | {k[5] or '–'} | {len(rs)} | {sum(r['failed'] for r in rs)} | "
                    f"{acc.mean():.3f} | {kl.mean():.3g}{sd(kl)} | {hs.mean():.3f}{sd(hs)} |")
    return "\n".join(rows)


def hypotheses_table(max_round: int) -> str:
    """One row per hypothesis with its verdict and N label."""
    p = RES / f"hypotheses_round{max_round}.json"
    if not p.exists():
        return "_not evaluated yet_"
    H = json.loads(p.read_text())["hypotheses"]
    rows = ["| Hypothesis | Verdict | Evidence size |", "|---|---|---|"]
    for k in ("H1", "H2", "H3", "H4", "H4b", "H5", "H6", "H7", "H8"):
        if k not in H:
            rows.append(f"| {k} | not evaluated yet | – |")
            continue
        h = H[k]
        v = h.get("verdict") or "; ".join(f"{a}: {b}" for a, b in h.get("verdicts", {}).items())
        rows.append(f"| {k} | {v} | {h.get('label', h.get('N', h.get('N_runs', '–')))} |")
    return "\n".join(rows)


def inject(path: Path, name: str, text: str) -> None:
    """Replace the marked block `name` in a markdown file (markers must already exist)."""
    s = path.read_text(encoding="utf-8")
    pat = re.compile(rf"(<!-- BEGIN {re.escape(name)} -->).*?(<!-- END {re.escape(name)} -->)", re.S)
    if not pat.search(s):
        raise KeyError(f"markers for {name} not found in {path}")
    path.write_text(pat.sub(lambda m: m.group(1) + "\n" + text.strip("\n") + "\n" + m.group(2), s), encoding="utf-8", newline="\n")
