"""Tests for the sixth audit's changes (deviation 13).

Local explanation: (1) the formal-verdict text shows §5's literal reading beside "cannot tell at this N" exactly when a
Holm-adjusted p is ≥ 0.05 at N > 1, and never for supported comparisons or at N = 1; (2) the read-through labels of
the agents' parameter searches are internally consistent (summary counts equal the per-run labels).
Global context: the predictions table in README/summary/paper is generated by `vmi.analysis.predictions`, and the
sweep count quoted in the paper (§3.3) and Appendix D comes from results/audit6/sweep_labels.json.
"""

from __future__ import annotations  # postponed annotations

import json  # labels file

import pytest  # skip when the results file is absent

from vmi.analysis.predictions import _verdict  # formal-verdict text
from vmi.config import REPO_ROOT  # results folder


def test_literal_reading_shown_for_cannot_tell_at_n3():
    h = {"N": 3, "verdicts": {"E3>W-freq": "cannot tell at this N", "E3>W-alg": "cannot tell at this N"},
         "holm_p": {"E3>W-freq": 0.2, "E3>W-alg": 0.7}}
    text = _verdict(h)
    assert "read literally" in text and '"not supported"' in text and "deviation 1" in text


def test_literal_reading_absent_when_supported_or_n1():
    assert "read literally" not in _verdict({"N": 3, "verdicts": {"E3": "supported"}, "holm_p": {"E3": 0.009}})
    assert "read literally" not in _verdict({"N": 1, "verdicts": {"E3>W-freq": "cannot tell at this N"},
                                             "holm_p": {"E3>W-freq": 1.0}})
    assert _verdict({"verdict": "supported"}) == "supported"


def test_sweep_labels_summary_matches_rows():
    p = REPO_ROOT / "results" / "audit6" / "sweep_labels.json"
    if not p.exists():
        pytest.skip("sweep labels not generated on this machine")
    d = json.loads(p.read_text(encoding="utf-8"))
    rows, s = d["rows"], d["summary"]
    assert s["runs"] == len(rows)
    assert s["read_sweep"] == sum(r["label"] == "sweep" for r in rows)
    assert s["regex_flagged"] == sum(r["regex_flagged"] for r in rows)
    assert s["regex_missed"] == sum(r["label"] == "sweep" and not r["regex_flagged"] for r in rows)
    assert {r["label"] for r in rows} <= {"sweep", "tuning-mention", "false-match", "none"}
    assert all(r["label"] in ("sweep", "tuning-mention", "false-match") for r in rows if r["regex_flagged"])
